import { Question } from '@/types/game';

/**
 * 100 soal Fiqih Lokal (Fiqih Ibadah) pilihan ganda.
 * Sumber: fikih ibadah.py — materi: Jamak Taqdim, Jamak Ta'khir, Shalat Qashar,
 * Shalat & Khutbah Jum'at, Pengurusan Jenazah, dan Hukum Isti'anah.
 */

type Tingkat = 'Mudah' | 'Sedang' | 'Sulit';
type Difficulty = 'easy' | 'medium' | 'hard' | 'very_hard';

interface RawQuestion {
  id: number;
  tingkat: Tingkat;
  materi: string;
  pertanyaan: string;
  pilihan: string[];
  /** Huruf pilihan jawaban benar: 'A' | 'B' | 'C' | 'D' */
  jawaban: string;
  pembahasan: string;
}

const DIFFICULTY_MAP: Record<Tingkat, Difficulty> = {
  Mudah: 'easy',
  Sedang: 'medium',
  Sulit: 'hard',
};

const DIFFICULTY_REWARD: Record<Difficulty, { timeLimit: number; coinsReward: number; movementReward: number }> = {
  easy: { timeLimit: 25, coinsReward: 15, movementReward: 2 },
  medium: { timeLimit: 30, coinsReward: 20, movementReward: 4 },
  hard: { timeLimit: 45, coinsReward: 25, movementReward: 6 },
  very_hard: { timeLimit: 60, coinsReward: 35, movementReward: 8 },
};

/** Membuang prefix "A. ", "B. " dst. karena label huruf sudah dirender oleh UI. */
function cleanOption(option: string): string {
  return option.replace(/^[A-D]\.\s*/, '').trim();
}

function toQuestion(raw: RawQuestion): Question {
  const difficulty = DIFFICULTY_MAP[raw.tingkat];
  const reward = DIFFICULTY_REWARD[difficulty];
  const options = raw.pilihan.map(cleanOption);
  const keyIndex = ['A', 'B', 'C', 'D'].indexOf(raw.jawaban.trim().toUpperCase());
  const correctAnswer = keyIndex >= 0 && keyIndex < options.length ? options[keyIndex] : cleanOption(raw.jawaban);

  return {
    id: `fiqih_${String(raw.id).padStart(3, '0')}`,
    type: 'multiple_choice',
    difficulty,
    category: 'Fiqih Lokal',
    subject: 'fiqih_lokal',
    text: raw.pertanyaan,
    options,
    correctAnswer,
    explanation: raw.pembahasan,
    ...reward,
    tags: ['Fiqih Lokal', raw.materi],
  };
}

