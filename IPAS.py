def cek_distribusi_jawaban(daftar_soal=BANK_SOAL):
    """Memeriksa distribusi posisi jawaban benar (1 sampai 4)."""
    hitung = Counter(item["jawaban_posisi"] for item in daftar_soal)
    return dict(sorted(hitung.items()))


def cetak_semua_soal(daftar_soal=BANK_SOAL, tampilkan_kunci=False):
    """Menampilkan seluruh soal tanpa label A, B, C, D."""
    bab_sekarang = None
    for item in daftar_soal:
        if item["bab"] != bab_sekarang:
            bab_sekarang = item["bab"]
            print(f"\n=== {bab_sekarang} ===\n")
        print(f"{item['no']}. {item['pertanyaan']}")
        for opsi in item["pilihan"]:
            print(f"   - {opsi}")
        if tampilkan_kunci:
            print(f"   [Kunci: Pilihan ke-{item['jawaban_posisi']} -> {item['jawaban_benar']}]")
        print()


def jalankan_kuis(jumlah_soal=10, acak=True):
    """Menjalankan simulasi kuis interaktif di terminal tanpa label A, B, C, D."""
    kumpulan = list(BANK_SOAL)
    if acak:
        random.shuffle(kumpulan)
    kumpulan = kumpulan[:jumlah_soal]

    skor = 0
    print(f"\nMemulai Kuis IPAS ({len(kumpulan)} Soal)")
    print("Masukkan angka posisi pilihan (1 - 4) sesuai urutan pilihan.\n")

    for idx, item in enumerate(kumpulan, start=1):
        print(f"Soal {idx}/{len(kumpulan)} [{item['bab']}]")
        print(item["pertanyaan"])
        for posisi, opsi in enumerate(item["pilihan"], start=1):
            print(f"  {posisi}. {opsi}")

        while True:
            jawaban_user = input("Jawaban kamu (1-4): ").strip()
            if jawaban_user in {"1", "2", "3", "4"}:
                break
            print("Input tidak valid. Ketik angka 1, 2, 3, atau 4.")

        if int(jawaban_user) == item["jawaban_posisi"]:
            print("Benar!\n")
            skor += 1
        else:
            print(f"Kurang tepat. Jawaban benar: {item['jawaban_benar']} (pilihan ke-{item['jawaban_posisi']})\n")

    nilai = (skor / len(kumpulan)) * 100 if kumpulan else 0
    print(f"Selesai! Skor akhir: {skor}/{len(kumpulan)} (Nilai: {nilai:.1f})")


