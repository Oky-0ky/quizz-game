def cetak_soal(nomor=None):
    """Mencetak soal berdasarkan nomor atau seluruh soal."""
    daftar = SOAL_FIKIH_IBADAH if nomor is None else [s for s in SOAL_FIKIH_IBADAH if s["no"] == nomor]
    for item in daftar:
        print(f"[{item['kategori']}] Soal No. {item['no']}:")
        print(item['soal'])
        for p in item['pilihan']:
            print(f"  {p}")
        print(f"Kunci Jawaban: {item['kunci']}\n" + "-"*50)

