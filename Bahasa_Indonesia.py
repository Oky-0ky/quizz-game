def cetak_semua_soal():
    print("=" * 80)
    print("BANK SOAL DAN KUNCI JAWABAN BAHASA INDONESIA (1-100)".center(80))
    print("=" * 80 + "\n")

    print("--- BAGIAN I: SOAL PILIHAN GANDA (1 - 70) ---\n")
    for q in SOAL_PILIHAN_GANDA:
        print(f"Soal No. {q['no']} [{q['tingkat']}]")
        print(f"{q['soal']}")
        for pil in q['pilihan']:
            print(f"  {pil}")
        print(f">> Kunci Jawaban: {q['kunci']}\n")

    print("\n" + "=" * 80)
    print("--- BAGIAN II: SOAL ESSAY & KUNCI JAWABAN (71 - 100) ---\n")
    for eq in SOAL_ESSAY:
        print(f"Soal No. {eq['no']} [{eq['tingkat']}]")
        print(f"{eq['soal']}")
        print(f">> Kunci Jawaban: {eq['jawaban']}\n")

if __name__ == "__main__":
    cetak_semua_soal()
